"""
compliance/__init__.py — SEBI-aware guardrails for IndiaScreen v3

WHY THIS EXISTS:
    v0.2's Telegram bot pushed unsolicited, automated "Strong Buy" / "Buy" /
    "Sell" calls to a distribution list every day at a fixed time, with no
    disclosure, no registration, and no distinction between "this stock
    matches a technical/fundamental filter" and "you should trade this."

    Since 2022, SEBI has progressively tightened rules on who may give
    investment advice and how automated "tips" may be distributed
    (Investment Adviser Regulations, and the 2023-2025 enforcement push
    against unregistered "finfluencers" and tip-selling Telegram/Discord
    channels). A daily auto-broadcast of "Buy"/"Sell" labels to a channel,
    generated by an algorithm and pushed without the recipient asking for
    that specific stock, sits squarely in the risk zone regulators have been
    acting on — regardless of the MIT license or the README disclaimer,
    because the *behavior* (algorithmic tip broadcast) is what's regulated,
    not just the wording.

    This module does not make legal determinations — it enforces a safer
    default posture:
      1. Screener output is described as "criteria matches" / "watchlist
         candidates", never as "Buy"/"Sell" recommendations.
      2. Every outbound message (Telegram, UI, exports) carries a
         non-advisory disclosure.
      3. Alerts are opt-in / pull-based by default (user must request a
         run), not push-based to a broadcast list — reducing the
         "unsolicited distribution" exposure.

    If you intend to operate this as a paid or public-facing service in
    India, consult a securities lawyer about SEBI Investment Adviser /
    Research Analyst registration requirements — this module is a
    harm-reduction default, not a compliance certification.
"""

from __future__ import annotations

SIGNAL_RELABEL = {
    "Strong Buy": "Strong Match (bullish criteria)",
    "Buy":        "Match (bullish criteria)",
    "Hold":       "Neutral / No Signal",
    "Sell":       "Match (bearish criteria)",
    "Strong Sell": "Strong Match (bearish criteria)",
}

NON_ADVISORY_FOOTER = (
    "\n\n---\n"
    "This is an automated output of a rules-based screen (technical + "
    "fundamental criteria you configured). It is *not* investment advice, "
    "a recommendation, or a solicitation to buy or sell any security. "
    "IndiaScreen and its authors are not SEBI-registered Investment "
    "Advisers or Research Analysts. Do your own research and consult a "
    "registered adviser before trading."
)

SHORT_DISCLAIMER = (
    "Educational/research tool only — not investment advice. Not a "
    "SEBI-registered adviser. See full disclaimer: /compliance/DISCLAIMER.md"
)


def relabel_signal(signal: str) -> str:
    """Map internal Buy/Sell-style labels to non-advisory language for display."""
    return SIGNAL_RELABEL.get(signal, signal)


def with_disclaimer(message: str, short: bool = False) -> str:
    """Append the appropriate disclaimer to any user-facing message/export."""
    return message + (SHORT_DISCLAIMER if short else NON_ADVISORY_FOOTER)


def relabel_dataframe_signals(df, column: str = "signal"):
    """Return a copy of df with the signal column relabeled for display/export."""
    if df is None or column not in getattr(df, "columns", []):
        return df
    out = df.copy()
    out[column] = out[column].map(lambda s: SIGNAL_RELABEL.get(s, s))
    return out
